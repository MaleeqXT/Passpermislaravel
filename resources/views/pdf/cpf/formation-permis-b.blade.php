    <h1>Informations Formation Permis B - Auto-école PassPermisFacile</h1>
    <p style="margin: 0 0 12px;">
        Détails complets de la formation Permis B, infos légales et pédagogiques, tarifs, documents et contact.
    </p>

    <h2>1. Description détaillée de la formation</h2>
    <p>
        La formation au permis de conduire catégorie B a pour objectif d'acquérir les compétences nécessaires pour conduire
        un véhicule léger (voiture particulière) en toute sécurité, dans le respect de la réglementation routière et des autres usagers.
    </p>
    <p>
        Elle comprend une formation théorique (préparation au code de la route) et une formation pratique (apprentissage de la conduite
        sur véhicule à boîte manuelle ou automatique).
    </p>
    <ul>
        <li>Avec Code de la Route (formation complète)</li>
        <li>Sans Code (formation pratique uniquement)</li>
    </ul>

    <h2>2. Objectifs de la formation</h2>
    <ul>
        <li>Maîtriser les règles de circulation et de sécurité routière.</li>
        <li>Développer une conduite responsable, économique et citoyenne.</li>
        <li>Être capable de circuler en toute autonomie et de présenter l'examen pratique du permis B.</li>
        <li>Obtenir la certification d'aptitude à la conduite délivrée par le ministère chargé des transports.</li>
    </ul>

    <h2>3. Public visé</h2>
    <p>
        Toute personne souhaitant obtenir le permis de conduire B pour des raisons personnelles ou professionnelles,
        y compris dans le cadre d'un financement via le Compte Personnel de Formation (CPF).
    </p>

    <h2>4. Prérequis</h2>
    <ul>
        <li>Aucun prérequis obligatoire.</li>
        <li>Être âgé de 17 ans minimum (ou 15 ans dans le cadre de la conduite accompagnée).</li>
        <li>Savoir lire et comprendre le français.</li>
        <li>Être apte médicalement à la conduite.</li>
    </ul>

    <h2>5. Modalités d'inscription</h2>
    <ul>
        <li>Inscription possible directement en ligne via le formulaire Être recontacté ou auprès de nos agences à Toulouse et Creil.</li>
        <li>Le dossier d'inscription est validé après :</li>
        <li>Signature du contrat de formation.</li>
        <li>Validation du financement (CPF ou autre).</li>
        <li>Transmission des pièces justificatives.</li>
    </ul>

    <h2>6. Délais d'accès</h2>
    <p>
        L'entrée en formation est possible en moyenne sous 15 jours après validation du dossier d'inscription et, le cas échéant,
        du financement CPF. Les dates sont ensuite planifiées selon les disponibilités du candidat et de nos moniteurs.
    </p>

    <h2>7. Durée moyenne de la formation</h2>
    <p>
        La durée dépend du forfait choisi (6 à 42 heures de conduite, avec ou sans code). Une évaluation initiale est réalisée avant
        le démarrage pour recommander le volume d'heures adapté.
    </p>

    <h2>8. Méthodes pédagogiques</h2>
    <ul>
        <li>Cours théoriques : préparation intensive au Code de la Route (10 heures présentielles).</li>
        <li>Cours pratiques : leçons individuelles sur véhicule à boîte manuelle ou automatique.</li>
        <li>Alternance d'explications, démonstrations, mises en situation réelles et retours pédagogiques.</li>
        <li>Suivi individualisé de la progression du stagiaire.</li>
    </ul>

    <h2>9. Modalités d'évaluation</h2>
    <ul>
        <li>Évaluation initiale : test de positionnement avant l'entrée en formation.</li>
        <li>Évaluations formatives tout au long du parcours pour suivre l'acquisition des compétences.</li>
        <li>Évaluation finale : présentation à l'examen théorique (si code) et à l'examen pratique du permis B.</li>
    </ul>

    <h2>10. Tarifs / Financement / CPF</h2>
    <p>
        Les forfaits proposés sont éligibles au CPF et varient selon le type de boîte (manuelle ou automatique) et selon que la
        formation inclut ou non la préparation au code de la route. Tous les forfaits comprennent l'inscription, les frais
        administratifs, les cours de code intensif (10 h en présentiel, pour les formules avec code), les heures de conduite et
        l'accompagnement à l'examen lorsque prévu.
    </p>

